//! Command icons shared by UI and tool definitions.

pub fn icon(name: &str) -> &'static str {
    match name {
        "transport.play" => "play",
        "transport.stop" => "stop",
        "transport.seek" => "skip-back",
        "history.undo" => "undo",
        "history.redo" => "redo",
        "history.list" => "history",
        "project.save" | "version.save" => "saved",
        "project.save-as" => "file",
        "project.open" => "open",
        "version.list" => "history",
        "export.mixdown" => "export",
        "export.stems" => "layers",
        "export.midi" => "midi",
        "export.dawproject" => "file",
        "track.add.audio" => "wave",
        "track.add.instrument" => "instrument",
        "track.add.bus" | "send.add.bus" => "bus",
        "track.mute" | "clip.mute" | "note.mute" => "mute",
        "track.solo" => "solo",
        "track.arm" => "record",
        "clip.split" | "note.split" => "cut",
        "view.snap" => "grid",
        "mixer.focus" => "mixer",
        "note.quantize" => "quant",
        "plugin.restart" | "plugin.reload" => "sync",
        "plugin.deactivate" | "plugin.activate" => "power",
        "plugin.stats" | "engine.stats" => "gauge",
        "prefs.get" => "gear",
        n if n.ends_with(".delete") => "trash",
        n if n.starts_with("transport.loop") || n.starts_with("loop.") => "loop",
        n if n.starts_with("record.") => "record",
        n if n.starts_with("folder.") => "folder",
        n if n.starts_with("note.") => "roll",
        n if n.starts_with("clip.") => "arrange",
        n if n.starts_with("track.") => "keys",
        n if n.starts_with("send.") => "send",
        n if n.starts_with("tempo.") => "tempo",
        _ => "prompt",
    }
}
