#[cfg(test)]
mod tests {
    use super::*;
    use crate::command::Registry;

    #[test]
    fn every_command_has_a_short_name_and_each_name_is_its_own() {
        let registry = Registry::standard();
        for def in registry.all() {
            let l = def
                .label()
                .unwrap_or_else(|| panic!("{} has no name", def.name));
            assert_eq!(registry.label(def.name), Some(l));
            // A name, not a sentence: no 「〜します」 and no full stop.
            assert!(!l.ends_with("ます") && !l.contains('。'), "{l}");
            assert!(l.chars().count() <= 20, "{l}");
        }
        let mut names = std::collections::BTreeSet::new();
        let mut labels = std::collections::BTreeSet::new();
        for (n, l) in LABELS {
            assert!(names.insert(*n), "{n} twice");
            assert!(labels.insert(*l), "{l} twice");
        }
        assert_eq!(label("no.such"), None);
    }
}
