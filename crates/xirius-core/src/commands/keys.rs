//! Default command bindings shared by the palette and keymap.

/// The kind of a row, for the keyboard picture's colours.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum Cat {
    Tool,
    Play,
    Edit,
    Track,
    View,
}

impl Cat {
    pub const ALL: [Cat; 5] = [Cat::Tool, Cat::Play, Cat::Edit, Cat::Track, Cat::View];

    pub fn name(self) -> &'static str {
        match self {
            Cat::Tool => "tool",
            Cat::Play => "play",
            Cat::Edit => "edit",
            Cat::Track => "track",
            Cat::View => "view",
        }
    }

    pub fn label(self) -> &'static str {
        match self {
            Cat::Tool => "ツール",
            Cat::Play => "再生",
            Cat::Edit => "編集",
            Cat::Track => "トラック",
            Cat::View => "表示",
        }
    }

    /// The kind of a command the catalog does not list, from its name.
    pub fn of(command: &str) -> Cat {
        let name = command.split_whitespace().next().unwrap_or("");
        let head = name.split('.').next().unwrap_or("");
        match head {
            "tool" => Cat::Tool,
            "transport" | "record" | "loop" => Cat::Play,
            "track" | "send" | "plugin" | "folder" => Cat::Track,
            "view" | "select" | "browser" => Cat::View,
            _ => Cat::Edit,
        }
    }
}

/// One row of the keymap: a command (with its arguments) in a context, and its keys in the
/// `studio-pro` preset.
